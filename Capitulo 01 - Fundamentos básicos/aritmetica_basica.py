"""Capítulo 01: Aritmética básica
Este arquivo mostra as operações matemáticas mais simples em Python.
"""

# Números inteiros e ponto flutuante
inteiro = 10
flutuante = 2.5
print('Inteiro:', inteiro)
print('Flutuante:', flutuante)

# Adição
adicao = 5 + 3
print('Adição:', adicao)

# Subtração
subtracao = 10 - 4
print('Subtração:', subtracao)

# Multiplicação
multiplicacao = 6 * 7
print('Multiplicação:', multiplicacao)

# Divisão normal
divisao = 20 / 5
print('Divisão:', divisao)

# Divisão inteira
divisao_inteira = 11 // 3
print('Divisão inteira:', divisao_inteira)

# Resto da divisão
resto = 10 % 3
print('Resto:', resto)

# Potenciação
potencia = 2 ** 3
print('Potência:', potencia)

# Ordem das operações
resultado1 = 2 + 3 * 4
resultado2 = (2 + 3) * 4
print('2 + 3 * 4 =', resultado1)
print('(2 + 3) * 4 =', resultado2)

# Misturar inteiro e float
mistura = 5 + 2.5
print('Inteiro + float =', mistura)
